package usersponsor

import (
	_ "embed"

	"github.com/Team-Haruki/Haruki-Toolbox-Backend/utils/codec/jsoncodec"
)

type FrameParts struct {
	Base        string `json:"base"`
	CenterTop   string `json:"centertop"`
	LeftTop     string `json:"lefttop"`
	RightTop    string `json:"righttop"`
	LeftBottom  string `json:"leftbottom"`
	RightBottom string `json:"rightbottom"`
}

type Frame struct {
	ID             string            `json:"id"`
	Name           map[string]string `json:"name"`
	Thumbnail      string            `json:"thumbnail"`
	PanelPreview   string            `json:"panelPreview"`
	ProfilePreview string            `json:"profilePreview"`
	Horizontal     FrameParts        `json:"horizontal"`
	Vertical       FrameParts        `json:"vertical"`
}

// Catalog paths are reviewed server assets; clients can select an ID only.
// The preview PNGs are generated by Drawing from these exact parts and
// synthetic profile data. They ship with the frontend.
//
//go:embed catalog.json
var catalogJSON []byte

func frameCatalog() []Frame {
	var frames []Frame
	if err := jsoncodec.Unmarshal(catalogJSON, &frames); err != nil {
		panic(err)
	}
	return frames
}

func findFrame(id string) *Frame {
	for _, frame := range frameCatalog() {
		if frame.ID == id {
			return &frame
		}
	}
	return nil
}
