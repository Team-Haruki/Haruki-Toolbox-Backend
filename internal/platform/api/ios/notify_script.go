package ios

// Script parts shared by the uploader script (script mode) and the proxy-mode
// notification script. Changing one changes both scripts: bump ScriptVersion
// and ProxyNotifyScriptVersion together with it.

// notifyArgumentJS reads the module's "notify" argument (see GenerateModule).
// Surge, Shadowrocket and Stash pass it as the string "notify=<value>", Loon
// as an object. Only an explicit off value turns notifications off; with no
// argument, or one the app left unfilled, notifyByDefault applies.
const notifyArgumentJS = `function notifyEnabled() {
    if (typeof $argument === "undefined" || $argument === null) return notifyByDefault;
    let value;
    if (typeof $argument === "object") {
        value = $argument.notify;
    } else {
        const text = String($argument).trim();
        const match = text.match(/(?:^|[&,;\s])notify\s*=\s*([^&,;\s]*)/i);
        value = match ? match[1] : (/^(true|false|on|off|1|0)$/i.test(text) ? text : undefined);
    }
    if (value === undefined || value === null) return notifyByDefault;
    value = String(value).trim();
    // An app that does not fill in arguments leaves {{{notify}}}, {notify} or
    // ${args.notify} as it is.
    if (value === "" || /[{}$]/.test(value)) return notifyByDefault;
    return !/^(false|0|off|no|关闭|关)$/i.test(value);
}`

// uploadErrorTextJS turns the upload endpoints' public error codes and
// messages into notification text.
const uploadErrorTextJS = `function uploadErrorText(code) {
    switch (code) {
        case "invalid upload code":
            return "上传码已失效：请到 Haruki 工具箱的 iOS 模块页面，用新的上传码重新安装模块。";
        case "upload not allowed":
        case "upload_not_allowed":
            return "这个游戏账号还没有在 Haruki 工具箱绑定并验证，或你没有它的上传授权。";
        case "invalid_upload_payload":
            return "工具箱无法解析这份数据，没有保存。";
        case "temporarily_unavailable":
            return "工具箱暂时无法处理，稍后重进游戏即可重试。";
        case "internal_error":
            return "工具箱保存数据时出错，稍后重进游戏即可重试。";
        case "game_server_unavailable":
            return "工具箱连不上游戏服务器，这次没有上传。";
        default:
            return "";
    }
}`

// ProxyNotifyScriptVersion is the proxy-mode notification script's version;
// bump it with every change to the script (see ScriptVersion).
const ProxyNotifyScriptVersion = "1.0.0"

// ProxyNotifyScriptPath is where the proxy-mode notification script is served,
// under the iOS route prefix.
const ProxyNotifyScriptPath = "/ios/script/proxy-notify.js"

// proxyNotifyScriptTemplate runs on the response of a proxy-mode upload,
// without its body (Loon runs such a script at the response header stage,
// https://nsloon.app/docs/Script/script_v2). The server reports the upload in
// X-Haruki-Upload-Result (ok, failed, skipped) and X-Haruki-Upload-Error; a
// response without them (not from the toolbox, or nothing uploaded) posts
// nothing.
const proxyNotifyScriptTemplate = `// Haruki Toolbox proxy-mode upload notification
// Generated by Haruki Toolbox
const scriptName = "haruki_toolbox_proxy_notify.js";
const version = "{{SCRIPT_VERSION}}";
const notifyByDefault = {{NOTIFY_DEFAULT}};
const regionLabels = { jp: "日服", en: "国际服", tw: "台服", kr: "韩服", cn: "国服" };

{{NOTIFY_ARGUMENT_JS}}

{{UPLOAD_ERROR_TEXT_JS}}

function headerValue(name) {
    const headers = (typeof $response !== "undefined" && $response && $response.headers) || {};
    const wanted = name.toLowerCase();
    for (const key of Object.keys(headers)) {
        if (key.toLowerCase() === wanted) return String(headers[key]);
    }
    return null;
}

function subject() {
    const url = (typeof $request !== "undefined" && $request && $request.url) || "";
    const match = url.match(/\/ios\/proxy\/([a-z]+)\//);
    const region = (match && regionLabels[match[1]]) || "";
    let data = "游戏";
    if (url.indexOf("/suite/") >= 0) data = "Suite";
    else if (url.indexOf("/birthday-party/") >= 0) data = "MySekai 生日派对";
    else if (url.indexOf("/mysekai") >= 0) data = "MySekai";
    return (region ? region + " " : "") + data + " 数据";
}

function post(subtitle, message) {
    if (typeof $notification !== "undefined") {
        $notification.post("Haruki 工具箱", subtitle, message);
    }
}

// A notification that throws must not keep the game waiting for its response.
try {
    const result = headerValue("X-Haruki-Upload-Result");
    if (notifyEnabled()) {
        if (result === "ok") {
            post(subject() + "已上传", "工具箱已保存这份数据，首页「我的账号」会显示这次的上传时间。");
        } else if (result === "failed") {
            post(subject() + "上传失败", uploadErrorText(headerValue("X-Haruki-Upload-Error") || "") || "工具箱没有保存这份数据，稍后重进游戏即可重试。");
        }
    }
} catch (e) {
    console.log("[" + scriptName + "-v" + version + "] notification failed: " + e);
}
$done({});
`
